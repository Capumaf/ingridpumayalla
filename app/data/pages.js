<p>As a Peruvian visual and performance female artist, I am interested in bringing into the narratives of my work stories and myths around nature, the consequences of its continual loss, and the impact on the native communities who inhabit it. In my work I am interested in portraying female figures and exploring their empowerment within pre-Colombian cultures in the north of Peru.I use this to create modern myths in order to address contemporary issues of displacement and loss. My work looks into the internal and external migrations in Peru to understand the causes and consequences in the identity of the land and its communities.I investigate and focus on the experience of 'dislocation', 'loss' and 'change' during these transitions.</p>

